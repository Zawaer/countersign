#!/usr/bin/env python3
"""Select the PR set for the historical replay (deterministic rule) and write dataset.yaml.

Rule: merged into develop or master between 2023-06-01 and 2026-06-30 (so every PR had at least 4.5 months for an
escape to surface before 2026-11-13), human author (no bots), not a branch-sync PR (title starts with Merge /
"v2 to master" / Touch-ups), and changes at least one .cs file under src/MessagePack.SourceGenerator,
src/MessagePack.Analyzers* or src/MessagePack (the v3 generator/analyzer and the runtime).
Mirror PRs (the same change merged into a second branch) are listed under `excluded` in labels.yaml.

Usage: python3 -I measurement/history/make_dataset.py [--repo /data/src/mp]
"""
import json, re, subprocess, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
repo = sys.argv[sys.argv.index("--repo") + 1] if "--repo" in sys.argv else "/data/src/mp"
git = lambda *a: subprocess.run(["git", "-C", repo, *a], capture_output=True, text=True, check=True).stdout  # noqa: E731
rows = []
for p in sorted(json.loads((HERE / "raw" / "prs.json").read_text()), key=lambda p: (p["mergedAt"], p["number"])):
    if not ("2023-06-01" <= p["mergedAt"] <= "2026-06-30") or p["baseRefName"] not in ("develop", "master"):
        continue
    if p["author"]["login"].startswith(("dependabot", "app/")) or re.match(r"(Merge|v2 to master|Touch-ups)", p["title"]):
        continue
    m = p["mergeCommit"]["oid"]
    base = git("rev-list", "--parents", "-n1", m).split()[1]
    files = git("diff", "--name-only", base, m).split()
    if any(re.match(r"src/(MessagePack\.SourceGenerator|MessagePack\.Analyzers[^/]*|MessagePack)/", f) and f.endswith(".cs") for f in files):
        rows.append({"number": p["number"], "title": p["title"], "merged": p["mergedAt"][:10], "base": p["baseRefName"],
                     "author": p["author"]["login"], "merge_commit": m})
import yaml  # noqa: E402
(HERE / "dataset.yaml").write_text("# Generated by make_dataset.py; do not edit. Labels live in labels.yaml.\n"
                                   + yaml.safe_dump({"dataset": rows}, sort_keys=False, allow_unicode=True, width=200))
print(len(rows), "PRs")
