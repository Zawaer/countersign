#!/bin/bash
# Offline .NET proof for red-team attempt G1 (REDTEAM.md): a Directory.Build.props one directory above a library
# compiles a file from tests/ into the shipped assembly. Needs only the .NET SDK (no packages, no network).
# usage: tests/redteam/dotnet_demos.sh [dotnet]      (S6 runs inside attacks.py when dotnet is found)
set -euo pipefail
DOTNET=${1:-$(command -v dotnet || echo /data/dotnet/dotnet)}
d=$(mktemp -d)
trap 'rm -rf "$d"' EXIT
mkdir -p "$d/src/Lib" "$d/tests/Shared"
cat > "$d/src/Lib/Lib.csproj" <<'X'
<Project Sdk="Microsoft.NET.Sdk">
  <PropertyGroup><TargetFramework>net9.0</TargetFramework><AssemblyName>MessagePack</AssemblyName></PropertyGroup>
</Project>
X
echo 'namespace MessagePack; public static class MessagePackSerializer { }' > "$d/src/Lib/Api.cs"
cat > "$d/src/Directory.Build.props" <<'X'
<Project>
  <ItemGroup Condition="'$(AssemblyName)' == 'MessagePack'">
    <Compile Include="$(MSBuildThisFileDirectory)../tests/Shared/Hook.g.cs" Link="Hook.g.cs" />
  </ItemGroup>
</Project>
X
cat > "$d/tests/Shared/Hook.g.cs" <<'X'
// <auto-generated/>
namespace MessagePack.Internal;
internal static class TestHook
{
    [System.Runtime.CompilerServices.ModuleInitializer]
    internal static void Init() => System.Environment.SetEnvironmentVariable("RT_HOOK_RAN", "1");
}
X
echo '<configuration><packageSources><clear /></packageSources></configuration>' > "$d/nuget.config"
export DOTNET_CLI_TELEMETRY_OPTOUT=1 DOTNET_NOLOGO=1 DOTNET_SKIP_FIRST_TIME_EXPERIENCE=1
"$DOTNET" build "$d/src/Lib/Lib.csproj" -nologo -v:q >/dev/null
if grep -qa TestHook "$d/src/Lib/bin/Debug/net9.0/MessagePack.dll"; then
  echo "G1: tests/Shared/Hook.g.cs is compiled into MessagePack.dll (type TestHook with a module initializer)"
else
  echo "G1: not reproduced"; exit 1
fi
